const fs = require('fs');
const path = require('path');
const os = require('os');
const { formatBytes } = require('./drives');

// Known Windows protected folders to skip during directory walks
const PROTECTED_DIRS = new Set([
  '$recycle.bin',
  'system volume information',
  'recovery',
  'msocache',
  'config.msi',
  'documents and settings',
  'windows'
]);

// Check if path is part of an installed Python runtime standard library
function isPythonStdLib(dirPath) {
  const normalized = dirPath.toLowerCase();
  return (
    (normalized.includes('\\python') || normalized.includes('\\python3')) &&
    (normalized.includes('\\lib\\') || normalized.endsWith('\\lib')) &&
    !normalized.includes('\\venv') &&
    !normalized.includes('\\.venv')
  );
}

/**
 * Calculates directory size and file count safely, ignoring symlinks and junctions.
 */
async function getDirectorySize(dirPath, onProgress) {
  let totalBytes = 0;
  let fileCount = 0;
  let dirCount = 0;

  async function walk(currentPath) {
    let entries;
    try {
      entries = await fs.promises.readdir(currentPath, { withFileTypes: true });
    } catch (e) {
      return;
    }

    for (const entry of entries) {
      if (entry.isSymbolicLink()) continue;

      const fullPath = path.join(currentPath, entry.name);
      try {
        if (entry.isDirectory()) {
          const lowerName = entry.name.toLowerCase();
          if (PROTECTED_DIRS.has(lowerName)) continue;
          dirCount++;
          await walk(fullPath);
        } else if (entry.isFile()) {
          const stat = await fs.promises.stat(fullPath);
          totalBytes += stat.size;
          fileCount++;
          if (onProgress && fileCount % 100 === 0) {
            onProgress({ currentPath: fullPath, fileCount, totalBytes });
          }
        }
      } catch (e) {
        // Skip inaccessible/locked files
      }
    }
  }

  await walk(dirPath);
  return { totalBytes, fileCount, dirCount };
}

/**
 * Checks if path exists safely
 */
function pathExists(targetPath) {
  try {
    return fs.existsSync(targetPath);
  } catch (e) {
    return false;
  }
}

