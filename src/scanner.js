/**
 * Scans all predefined bloat areas and returns categorized results
 */
async function scanBloatAreas(onProgress) {
  const definitions = getPredefinedCategories();
  const results = [];
  let totalDiscoveredBytes = 0;
  let totalDiscoveredFiles = 0;

  for (let i = 0; i < definitions.length; i++) {
    const item = definitions[i];
    if (onProgress) {
      onProgress({
        currentCategory: item.category,
        currentItem: item.name,
        currentPath: item.path,
        itemIndex: i + 1,
        totalItems: definitions.length,
        totalDiscoveredBytes,
        totalDiscoveredFiles
      });
    }

    if (!pathExists(item.path)) {
      continue;
    }

    try {
      const { totalBytes, fileCount, dirCount } = await getDirectorySize(item.path, (p) => {
        if (onProgress) {
          onProgress({
            currentCategory: item.category,
            currentItem: item.name,
            currentPath: p.currentPath,
            itemIndex: i + 1,
            totalItems: definitions.length,
            totalDiscoveredBytes: totalDiscoveredBytes + p.totalBytes,
            totalDiscoveredFiles: totalDiscoveredFiles + p.fileCount
          });
        }
      });

      if (totalBytes > 0 || fileCount > 0) {
        totalDiscoveredBytes += totalBytes;
        totalDiscoveredFiles += fileCount;

        results.push({
          ...item,
          totalBytes,
          fileCount,
          dirCount,
          formattedSize: formatBytes(totalBytes),
          exists: true
        });
      }
    } catch (e) {
      // Ignored
    }
  }

  // Sort by size descending
  results.sort((a, b) => b.totalBytes - a.totalBytes);

  return {
    items: results,
    totalBytes: totalDiscoveredBytes,
    totalFiles: totalDiscoveredFiles,
    formattedTotal: formatBytes(totalDiscoveredBytes)
  };
}

/**
 * Targets for developer projects
 */
const DEV_DIR_NAMES = new Set([
  'node_modules',
  '.next',
  '.nuxt',
  '.turbo',
  '.parcel-cache',
  'target', // Rust
  '__pycache__',
  '.pytest_cache',
  '.mypy_cache',
  '.tox',
  '.venv',
  'venv',
  'bin', // .NET
  'obj', // .NET
  '.gradle'
]);

/**
 * Fast search for developer bloat across any drive or directory
 */
async function scanProjectBloat(rootPath, options = {}, onProgress) {
  const maxDepth = options.maxDepth || 6;
  const foundItems = [];
  let totalBytes = 0;
  let totalFiles = 0;
  let scannedCount = 0;

  async function walk(currentPath, depth) {
    if (depth > maxDepth) return;

    let entries;
    try {
      entries = await fs.promises.readdir(currentPath, { withFileTypes: true });
    } catch (e) {
      return;
    }

    for (const entry of entries) {
      if (entry.isSymbolicLink()) continue;
      if (!entry.isDirectory()) continue;

      const name = entry.name;
      const lowerName = name.toLowerCase();

      // Skip Windows protected system directories
      if (PROTECTED_DIRS.has(lowerName)) continue;
      // Skip git internal files
      if (lowerName === '.git') continue;
      // Skip Python standard library internals
      if (isPythonStdLib(currentPath)) continue;

      const fullPath = path.join(currentPath, name);
      scannedCount++;

      if (onProgress && scannedCount % 50 === 0) {
        onProgress({
          scannedCount,
          currentPath: fullPath,
          foundCount: foundItems.length,
          totalBytes
        });
      }

      // Check if this folder is a dev artifact
      if (DEV_DIR_NAMES.has(name)) {
        // Confirm context
        let isMatch = false;
        let artifactType = name;

        if (name === 'node_modules') {
          isMatch = true;
          artifactType = 'Node.js Dependencies';
        } else if (name === '.next' || name === '.nuxt' || name === '.turbo' || name === '.parcel-cache') {
          isMatch = true;
          artifactType = 'Web Build Artifacts';
        } else if (name === 'target') {
          // Check if parent has Cargo.toml or Cargo.lock
          if (pathExists(path.join(currentPath, 'Cargo.toml')) || pathExists(path.join(currentPath, 'Cargo.lock'))) {
            isMatch = true;
            artifactType = 'Rust Build Target';
          }
        } else if (name === 'bin' || name === 'obj') {
          // Check if any .csproj or .sln in currentPath or parent
          try {
            const siblings = await fs.promises.readdir(currentPath);
            if (siblings.some(s => s.endsWith('.csproj') || s.endsWith('.sln') || s.endsWith('.fsproj'))) {
              isMatch = true;
              artifactType = `.NET ${name.toUpperCase()} Output`;
            }
          } catch (e) {}
        } else if (name === '__pycache__' || name === '.pytest_cache' || name === '.mypy_cache' || name === '.tox') {
          isMatch = true;
          artifactType = 'Python Bytecode/Cache';
        } else if (name === '.venv' || name === 'venv') {
          // Check if pyvenv.cfg exists
          if (pathExists(path.join(fullPath, 'pyvenv.cfg'))) {
            isMatch = true;
            artifactType = 'Python VirtualEnv';
          }
        } else if (name === '.gradle') {
          isMatch = true;
          artifactType = 'Gradle Cache';
        }

        if (isMatch) {
          const stats = await getDirectorySize(fullPath);
          if (stats.totalBytes > 0) {
            totalBytes += stats.totalBytes;
            totalFiles += stats.fileCount;
            let mtime = null;
            try {
              const stat = await fs.promises.stat(fullPath);
              mtime = stat.mtime;
            } catch (e) {}

            foundItems.push({
              path: fullPath,
              name,
              parentDir: currentPath,
              type: artifactType,
              totalBytes: stats.totalBytes,
              fileCount: stats.fileCount,
              formattedSize: formatBytes(stats.totalBytes),
              lastModified: mtime ? mtime.toISOString().split('T')[0] : 'Unknown'
            });
          }
          // Do NOT recurse into matched dev dir (saves time and avoids double count)
          continue;
        }
      }

      // Recurse down
      await walk(fullPath, depth + 1);
    }
  }

  await walk(rootPath, 1);
  foundItems.sort((a, b) => b.totalBytes - a.totalBytes);

  return {
    items: foundItems,
    totalBytes,
    totalFiles,
    formattedTotal: formatBytes(totalBytes)
  };
}

